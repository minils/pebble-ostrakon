/* =========================================================
 * Settings page, bundled with the app and opened as a data: URI
 * so no external server is involved in handling the access token.
 * Current settings are passed in via the URL hash, because a
 * data: URI page has no persistent localStorage of its own.
 * ========================================================= */
module.exports = [
  '<!DOCTYPE html>',
  '<html>',
  '<head>',
  '  <meta charset="utf-8">',
  '  <meta name="viewport" content="width=device-width, initial-scale=1">',
  '  <title>Memos Settings</title>',
  '  <style>',
  '    body {',
  '      font-family: sans-serif;',
  '      padding: 10px;',
  '    }',
  '    label {',
  '      display: block;',
  '      margin-top: 12px;',
  '    }',
  '    input[type=checkbox] {',
  '      width: auto;',
  '      margin-right: 8px;',
  '    }',
  '    input, textarea {',
  '      width: 100%;',
  '      font-size: 14px;',
  '      box-sizing: border-box;',
  '    }',
  '    button {',
  '      margin-top: 20px;',
  '      width: 100%;',
  '      padding: 10px;',
  '      font-size: 16px;',
  '    }',
  '    #test {',
  '      margin-top: 12px;',
  '    }',
  '    #test-result {',
  '      margin-top: 8px;',
  '      min-height: 1.2em;',
  '    }',
  '    .ok { color: #1a7f37; }',
  '    .error { color: #cf222e; }',
  '    .hint { color: #666; font-size: 13px; }',
  '  </style>',
  '</head>',
  '<body>',
  '',
  '<h2>Memos Settings</h2>',
  '',
  '<label>',
  '  Memos Server URL',
  '  <input id="url" type="text" placeholder="https://memos.example.com">',
  '</label>',
  '',
  '<label>',
  '  Access Token',
  '  <input id="token" type="text" placeholder="Your API token">',
  '</label>',
  '',
  '<button id="test" type="button">Test connection</button>',
  '<div id="test-result"></div>',
  '',
  '<label>',
  '  Default Tags (space-separated)',
  '  <input id="tags" type="text" placeholder="#pebble #notes">',
  '</label>',
  '',
  '<label>',
  '  To-do Tag (open tasks are shown in the app launcher)',
  '  <input id="todoTag" type="text" placeholder="#todo">',
  '</label>',
  '',
  '<label>',
  '  <input id="vibrate" type="checkbox" checked>',
  '  Vibrate on success and errors',
  '</label>',
  '',
  '<button id="save">Save</button>',
  '',
  '<script>',
  '  // Load existing settings passed in by the app',
  '  if (location.hash.length > 1) {',
  '    try {',
  '      var s = JSON.parse(decodeURIComponent(location.hash.substring(1)));',
  '      document.getElementById("url").value = s.url || "";',
  '      document.getElementById("token").value = s.token || "";',
  '      document.getElementById("tags").value = s.tags || "";',
  '      document.getElementById("todoTag").value = s.todoTag || "";',
  '      document.getElementById("vibrate").checked = s.vibrate !== false;',
  '    } catch (e) {',
  '      console.log("Failed to parse passed settings:", e);',
  '    }',
  '  }',
  '',
  '  function showResult(text, cls) {',
  '    var result = document.getElementById("test-result");',
  '    result.textContent = text;',
  '    result.className = cls;',
  '  }',
  '',
  '  // The server may not allow requests from this page (CORS); the watch',
  '  // also reports the connection status after saving.',
  '  document.getElementById("test").addEventListener("click", function() {',
  '    var url = document.getElementById("url").value.trim()',
  '      .replace(/\\/+$/, "").replace(/\\/api\\/v1\\/memos$/, "");',
  '    var token = document.getElementById("token").value.trim();',
  '    if (!url || !token) {',
  '      showResult("Enter the server URL and token first.", "error");',
  '      return;',
  '    }',
  '    showResult("Testing...", "hint");',
  '    var xhr = new XMLHttpRequest();',
  '    xhr.open("GET", url + "/api/v1/memos?pageSize=1", true);',
  '    xhr.setRequestHeader("Authorization", "Bearer " + token);',
  '    xhr.timeout = 10000;',
  '    xhr.onload = function() {',
  '      if (xhr.status >= 200 && xhr.status < 300) {',
  '        showResult("Connected. URL and token work.", "ok");',
  '      } else if (xhr.status === 401 || xhr.status === 403) {',
  '        showResult("The server rejected the token (" + xhr.status + ").", "error");',
  '      } else if (xhr.status === 404) {',
  '        showResult("No Memos API found at this URL (404).", "error");',
  '      } else {',
  '        showResult("Server error " + xhr.status + ".", "error");',
  '      }',
  '    };',
  '    xhr.onerror = xhr.ontimeout = function() {',
  '      showResult("Could not test from this page. Save, and the watch will " +',
  '        "show whether the connection works.", "hint");',
  '    };',
  '    xhr.send();',
  '  });',
  '',
  '  document.getElementById("save").addEventListener("click", function() {',
  '    var settings = {',
  '      url: document.getElementById("url").value.trim(),',
  '      token: document.getElementById("token").value.trim(),',
  '      tags: document.getElementById("tags").value.trim(),',
  '      todoTag: document.getElementById("todoTag").value.trim(),',
  '      vibrate: document.getElementById("vibrate").checked',
  '    };',
  '',
  '    // Return settings to Pebble app',
  '    document.location = "pebblejs://close#" +',
  '      encodeURIComponent(JSON.stringify(settings));',
  '  });',
  '</script>',
  '',
  '</body>',
  '</html>'
].join('\n');
