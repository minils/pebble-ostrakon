/* =========================================================
 * Settings page, bundled with the app and opened as a data: URI
 * so no external server is involved in handling the access token.
 * Current settings are passed in via the URL hash, because a
 * data: URI page has no persistent localStorage of its own.
 * ========================================================= */
module.exports = [
  '<!DOCTYPE html>',
  '<html>',
  '<head>',
  '  <meta charset="utf-8">',
  '  <meta name="viewport" content="width=device-width, initial-scale=1">',
  '  <title>Memos Settings</title>',
  '  <style>',
  '    body {',
  '      font-family: sans-serif;',
  '      padding: 10px;',
  '    }',
  '    label {',
  '      display: block;',
  '      margin-top: 12px;',
  '    }',
  '    input[type=checkbox] {',
  '      width: auto;',
  '      margin-right: 8px;',
  '    }',
  '    input, textarea {',
  '      width: 100%;',
  '      font-size: 14px;',
  '      box-sizing: border-box;',
  '    }',
  '    button {',
  '      margin-top: 20px;',
  '      width: 100%;',
  '      padding: 10px;',
  '      font-size: 16px;',
  '    }',
  '  </style>',
  '</head>',
  '<body>',
  '',
  '<h2>Memos Settings</h2>',
  '',
  '<label>',
  '  Memos Server URL',
  '  <input id="url" type="text" placeholder="https://memos.example.com">',
  '</label>',
  '',
  '<label>',
  '  Access Token',
  '  <input id="token" type="text" placeholder="Your API token">',
  '</label>',
  '',
  '<label>',
  '  Default Tags (space-separated)',
  '  <input id="tags" type="text" placeholder="#pebble #notes">',
  '</label>',
  '',
  '<label>',
  '  <input id="vibrate" type="checkbox" checked>',
  '  Vibrate on success and errors',
  '</label>',
  '',
  '<button id="save">Save</button>',
  '',
  '<script>',
  '  // Load existing settings passed in by the app',
  '  if (location.hash.length > 1) {',
  '    try {',
  '      var s = JSON.parse(decodeURIComponent(location.hash.substring(1)));',
  '      document.getElementById("url").value = s.url || "";',
  '      document.getElementById("token").value = s.token || "";',
  '      document.getElementById("tags").value = s.tags || "";',
  '      document.getElementById("vibrate").checked = s.vibrate !== false;',
  '    } catch (e) {',
  '      console.log("Failed to parse passed settings:", e);',
  '    }',
  '  }',
  '',
  '  document.getElementById("save").addEventListener("click", function() {',
  '    var settings = {',
  '      url: document.getElementById("url").value.trim(),',
  '      token: document.getElementById("token").value.trim(),',
  '      tags: document.getElementById("tags").value.trim(),',
  '      vibrate: document.getElementById("vibrate").checked',
  '    };',
  '',
  '    // Return settings to Pebble app',
  '    document.location = "pebblejs://close#" +',
  '      encodeURIComponent(JSON.stringify(settings));',
  '  });',
  '</script>',
  '',
  '</body>',
  '</html>'
].join('\n');
